"""Диалоги для проверки всего конвейера. turns — реплики покупателя; после clarify/no_match раннер сам
добавляет реплику ассистента. expect[i]: "clarify" | "result" (ok или no_match — как покажет перебор) | "ok" | "no_match".
fields[i] — ожидаемый набор полей clarify. want — условия, по которым проверяется итоговый ответ."""


def W(city, budget, cats, *cons):
    return {"city": city, "budget": budget, "cats": list(cats), "cons": list(cons)}


